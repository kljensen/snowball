// Test a large set of words for which we know
// the correct stemmed form.
func Test_PortugueseVocabulary(t *testing.T) {
	for _, testCase := range testCases {
		result := portuguese.Stem(testCase.in, true)
		if result != testCase.out {
			t.Errorf("Expected %v -> %v, but got %v", testCase.in, testCase.out, result)
		}
	}
}

func Benchmark_Stem(b *testing.B) {
	b.ReportAllocs()
	var bytes int
	// Add up the bytes
	for _, tc := range testCases {
		bytes += len(tc.in)
	}
	b.SetBytes(int64(bytes))
	b.ResetTimer()

	for i := 0; i < b.N; i++ {
		for _, tc := range testCases {
			portuguese.Stem(tc.in, true)
		}
	}
}

